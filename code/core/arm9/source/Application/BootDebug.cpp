static void clearMap()
{
    for (u32 i = 0; i < 32 * 32; ++i)
        UI_MAP_BASE[i] = 0;
}

static void putChar(u32 x, u32 y, char c)
{
    if (x >= 32 || y >= 32) return;
    u8 uc = static_cast<u8>(c);
    if (uc < 32 || uc > 126) uc = '?';
    UI_MAP_BASE[y * 32 + x] = static_cast<u16>(uc - 32);
}

static void printText(u32 x, u32 y, const char* text, u32 maxChars = 32)
{
    if (!text) return;
    while (*text && x < 32 && maxChars--)
        putChar(x++, y, *text++);
}

static void initFont()
{
    UI_PALETTE[0] = 0x0000;
    UI_PALETTE[1] = 0x7FFF;

    for (u32 g = 0; g < 95; ++g)
    {
        volatile u8* tile = UI_TILE_BASE + g * 32;
        for (u32 y = 0; y < 8; ++y)
        {
            const u8 bits = sFont8x8[g][y];
            for (u32 pair = 0; pair < 4; ++pair)
            {
                const u32 x = pair * 2;
                const u8 p0 = (bits >> x) & 1;
                const u8 p1 = (bits >> (x + 1)) & 1;
                tile[y * 4 + pair] = p0 | (p1 << 4);
            }
        }
    }
}

static void drawClosedButtonFramebuffer()
{
    // Bit 15 is set so the same pixels are also valid as direct-color data if
    // a future display path samples this strip through a bitmap BG.
    const u16 black = 0x8000;
    const u16 white = 0xFFFF;

    for (u32 y = UI_CLOSED_Y0; y < UI_CLOSED_Y1; ++y)
    {
        volatile u16* row = UI_VRAM_B_LCDC + y * 256;
        for (u32 x = 0; x < 256; ++x)
            row[x] = black;
    }

    static const char text[] = "X: CHEAT";
    u32 px = UI_CLOSED_TEXT_X;
    for (u32 i = 0; text[i]; ++i, px += 8)
    {
        u8 c = static_cast<u8>(text[i]);
        if (c < 32 || c > 126) c = '?';
        const u8* glyph = sFont8x8[c - 32];
        for (u32 gy = 0; gy < 8; ++gy)
        {
            const u8 bits = glyph[gy];
            volatile u16* row = UI_VRAM_B_LCDC + (UI_CLOSED_TEXT_Y + gy) * 256;
            for (u32 gx = 0; gx < 8; ++gx)
            {
                if ((bits >> gx) & 1)
                    row[px + gx] = white;
            }
        }
    }
}

void BootDebug_PrepareClosedButton()
{
    // VRAM B is kept out of the C/D capture ping-pong. Temporarily map it to
    // LCDC so ARM9 can prepare the 16-line framebuffer, then immediately put
    // it back at the stock MAIN_BG +0x40000 mapping. HBlank will expose B only
    // for scanlines 176..191 and VBlank restores it before the next frame.
    UI_REG_VRAM_B_CR = 0x80; // LCDC
    drawClosedButtonFramebuffer();
    UI_REG_VRAM_B_CR = 0x91; // MAIN_BG, offset 0x40000
}

void BootDebug_RestoreVideo()
{
    // Center-and-mask normally places the Main Engine on the bottom LCD and
    // blacks it out, while the Sub Engine displays the captured/centered GBA
    // image on the top LCD. Keep that top path untouched. Save the Main Engine
    // state, temporarily give VRAM B to Main BG slot 0, and use BG0 for the
    // cheat list on the bottom LCD.
    sMenuVideoState.dispcnt = UI_REG_DISPCNT;
    sMenuVideoState.bg0cnt = UI_REG_BG0CNT;
    sMenuVideoState.bg0hofs = UI_REG_BG0HOFS;
    sMenuVideoState.bg0vofs = UI_REG_BG0VOFS;
    sMenuVideoState.masterBright = UI_REG_MASTER_BRIGHT;
    sMenuVideoState.vramA = UI_REG_VRAM_A_CR;
    sMenuVideoState.vramB = UI_REG_VRAM_B_CR;
    sMenuVideoState.palette0 = UI_PALETTE[0];
    sMenuVideoState.palette1 = UI_PALETTE[1];
    sMenuVideoState.valid = 1;

    // VRAM A normally owns Main BG slot 0. Disable it only while the VM is
    // paused, then map VRAM B there for the text UI. C/D remain untouched, so
    // the frozen top-screen capture stays byte-for-byte intact.
    UI_REG_VRAM_A_CR = 0x00;
    UI_REG_VRAM_B_CR = 0x81; // MAIN_BG, offset 0x00000

    UI_REG_DISPCNT = (1u << 16) | (1u << 8); // graphics display, mode 0, BG0
    UI_REG_BG0CNT = (8u << 8);                // map base 8 -> 0x06004000
    UI_REG_BG0HOFS = 0;
    UI_REG_BG0VOFS = 0;
    UI_REG_MASTER_BRIGHT = 0;

    initFont();
    clearMap();
}

// Kept as no-ops so any leftover diagnostic call cannot paint old boot text.
void BootDebug_Init() { }
void BootDebug_Stage(u32) { }

void BootDebug_EnableBottomBacklight()
{
    // Do not touch SUB master brightness here: in centered gameplay the sub
    // engine is the visible top-screen GBA image and its brightness comes from
    // the user's display setting. Menu setup sets its own brightness separately.
    sysipc_setBottomBacklight(true);
}

void BootDebug_ShowCheatButton()
{
    printText(UI_CHEAT_COL, UI_CHEAT_ROW, "X: CHEAT", 8);
}

void BootDebug_Hide()
{
    if (!sMenuVideoState.valid)
        return;

    // Blank the temporary Main Engine while its VRAM mapping is being put
    // back, then restore exactly what the running GBA renderer had on menu
    // entry. The top-screen Sub Engine was never altered.
    UI_REG_MASTER_BRIGHT = 0x8010;
    clearMap();

    UI_PALETTE[0] = sMenuVideoState.palette0;
    UI_PALETTE[1] = sMenuVideoState.palette1;
    UI_REG_VRAM_B_CR = 0x00;
    UI_REG_VRAM_A_CR = sMenuVideoState.vramA;
    UI_REG_VRAM_B_CR = sMenuVideoState.vramB;

    UI_REG_BG0CNT = sMenuVideoState.bg0cnt;
    UI_REG_BG0HOFS = sMenuVideoState.bg0hofs;
    UI_REG_BG0VOFS = sMenuVideoState.bg0vofs;
    UI_REG_DISPCNT = sMenuVideoState.dispcnt;
    UI_REG_MASTER_BRIGHT = sMenuVideoState.masterBright;

    sMenuVideoState.valid = 0;
}
